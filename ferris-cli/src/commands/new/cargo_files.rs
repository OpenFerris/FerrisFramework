//! The scaffolded `Cargo.toml` and `.cargo/config.toml`.

use anyhow::Result;
use std::fs;
use std::path::Path;

/// A component `Cargo.toml`: `cdylib` for `wasm32-wasip2`, no framework
/// dependency — only `wit-bindgen` for the guest glue. The `[workspace]` table
/// keeps it a standalone crate.
pub(super) fn render_cargo_toml(name: &str) -> String {
    format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2021"
description = "{name} — Ferris app (WIT/WASM component)"
license = "MIT"
authors = ["You <you@example.com>"]

[lib]
crate-type = ["cdylib"]
path = "src/lib.rs"

# Generated by `ferris new`: the app is compute (guest) only. It never links
# the framework; it imports its services through the `wit/ferris.wit` contract
# and implements every export of the `ferris-app` world (`describe`, the
# request/stream/job handlers and the UI hooks).
[dependencies]
wit-bindgen = "0.62"

[workspace]
"#
    )
}

pub(super) fn write_cargo_toml(project_dir: &Path, name: &str) -> Result<()> {
    fs::write(project_dir.join("Cargo.toml"), render_cargo_toml(name))?;
    Ok(())
}

/// Default the build target to `wasm32-wasip2` so a plain `cargo build`
/// produces the core module the framework wraps into a component.
pub(super) fn render_cargo_config() -> &'static str {
    "[build]\ntarget = \"wasm32-wasip2\"\n"
}

pub(super) fn write_cargo_config(project_dir: &Path) -> Result<()> {
    fs::write(
        project_dir.join(".cargo").join("config.toml"),
        render_cargo_config(),
    )?;
    Ok(())
}
