//! The grid's squares: a workspace, a folder, their caption, and the small
//! arrange-mode controls.
//!
//! A tile is an icon square **and** its name in the flow below it. The caption is
//! not a tooltip: it is always on, and it owns its height, so the next row starts
//! below it instead of the name floating over another icon. That is why the
//! caption is a block rather than an absolutely positioned overlay.
//!
//! Both kinds draw through [`DeskGlyph`], which accepts an icon name or an
//! app-declared SVG document: the grid is the one place an SVG icon is rendered
//! (the sidebar and menus keep using names, because they are one line high).

use leptos::prelude::*;

use crate::components::ui::icon::Icon;
use crate::desk::icon::DeskGlyph;
use crate::desk::session::DeskIcon;
use crate::i18n::{DeskI18n, use_i18n};

use super::dom::Seam;

/// The icon a folder gets until the user picks another one.
pub(super) const DEFAULT_FOLDER_ICON: &str = "Folder";
/// The icon a workspace gets when the app declared none.
const DEFAULT_WORKSPACE_ICON: &str = "layout-dashboard";

/// The icons a folder can be given, as (value, name). A short list on purpose:
/// the point of the grid is that an icon reads at a glance, and the full set is
/// a searchable dialog of its own.
pub(super) const FOLDER_ICONS: [(&str, &str); 8] = [
    ("Folder", "folder"),
    ("Boxes", "boxes"),
    ("Briefcase", "briefcase"),
    ("Building2", "building-2"),
    ("Truck", "truck"),
    ("Receipt", "receipt"),
    ("Users", "users"),
    ("Wrench", "wrench"),
];

/// The accents a folder can wear, as (value, class).
///
/// The class names are written out whole rather than composed from the value
/// (`ferris-desk-folder--{value}`) because the stylesheet is generated by
/// scanning the source for class names: a name built at runtime is in no
/// stylesheet, so the swatch would render as no colour at all.
pub(super) const FOLDER_COLORS: [(&str, &str); 6] = [
    ("slate", "ferris-desk-folder--slate"),
    ("blue", "ferris-desk-folder--blue"),
    ("emerald", "ferris-desk-folder--emerald"),
    ("amber", "ferris-desk-folder--amber"),
    ("rose", "ferris-desk-folder--rose"),
    ("violet", "ferris-desk-folder--violet"),
];

/// What the grid looks like while nothing is being arranged.
///
/// The square is a comfortable target that still reads as an icon rather than a
/// banner: large enough for a 2.25rem glyph and for a finger, small enough that
/// the caption underneath keeps the whole tile compact. The name is plain text in
/// the flow (see [`TileCaption`]) — no tooltip, no background — and the column is
/// fixed width (`w-20`) so captions line up across rows.
const TILE: &str = "flex size-16 items-center justify-center rounded-2xl transition-transform \
                    hover:scale-105 focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50";
/// The grid itself: loose workspaces and folders share one responsive grid, so
/// an app that declares no folders gets a plain grid of workspace icons.
#[component]
pub(super) fn IconGrid(
    icons: Vec<DeskIcon>,
    editing: ReadSignal<bool>,
    over: ReadSignal<Option<Seam>>,
) -> impl IntoView {
    view! {
        <ul class="grid grid-cols-3 gap-4 sm:grid-cols-4 lg:grid-cols-6" data-name="DesktopIcons">
            {icons
                .into_iter()
                .map(|icon| {
                    if icon.is_folder() {
                        view! { <FolderTile icon=icon editing=editing over=over /> }.into_any()
                    } else {
                        view! { <WorkspaceTile icon=icon editing=editing over=over /> }.into_any()
                    }
                })
                .collect_view()}
        </ul>
    }
}

/// One workspace: an icon square with its name written underneath.
///
/// The name is plain text, always visible (the old tooltip-only caption made the
/// resting grid a set of unnamed squares), and its fixed block height is what
/// reserves the room under the icon. `title` stays as the accessible/long-press
/// label, and gets the hidden marker when the workspace is parked.
#[component]
fn WorkspaceTile(
    icon: DeskIcon,
    editing: ReadSignal<bool>,
    over: ReadSignal<Option<Seam>>,
) -> impl IntoView {
    let key = icon
        .icon
        .clone()
        .unwrap_or_else(|| DEFAULT_WORKSPACE_ICON.to_string());
    let name = icon.id.clone();
    let label = icon.label.clone();
    let caption = label.clone();
    let accessible = label.clone();
    // Whether this tile is the one a drag would land on. Derived from a copy of
    // the id, because the id itself is also written to attributes and the drag
    // highlight has to outlive them.
    let id = name.clone();
    let seam = name.clone();
    let highlighted = Signal::derive(move || over.get().as_ref().is_some_and(|s| s.id == id));
    let side = Signal::derive(move || over.get().and_then(|s| (s.id == seam).then_some(s.after)));
    let hidden = icon.hidden;
    let controls = name.clone();
    // A hidden icon is parked under the grid, not on it: it is dimmed so it does
    // not read as one more workspace, and it cannot be picked up, because moving
    // something that is off the desk is not a move.
    let parked = move || hidden;
    let liftable = move || editing.get() && !hidden;
    // `StoredValue` keeps the translator `Copy`, so the two reactive labels can
    // share it.
    let i18n = use_i18n();
    let tr_with = move |key: &str, args: &[(&str, &str)]| {
        i18n.with_value(|i18n: &DeskI18n| i18n.t_with(key, args))
    };

    view! {
        <li
            data-icon=name
            class="group/tile relative flex w-20 flex-col items-center pb-1"
            class:opacity-40=parked
        >
            <button
                type="button"
                data-name="WorkspaceIcon"
                data-workspace=name.clone()
                title=move || {
                    if hidden {
                        tr_with("desk.desktop.hidden_marker", &[("label", &label)])
                    } else {
                        label.clone()
                    }
                }
                aria-label=move || {
                    if hidden {
                        tr_with("desk.desktop.hidden_marker", &[("label", &accessible)])
                    } else {
                        accessible.clone()
                    }
                }
                draggable=move || liftable().to_string()
                class=format!("{TILE} bg-primary/10 text-primary")
                class:cursor-grab=liftable
                class:ring-2=highlighted
                class:ring-ring=highlighted
            >
                <DeskGlyph icon=key class="size-9" />
            </button>
            <TileCaption label=caption />
            <TileSeam side=side />
            {move || {
                if !editing.get() {
                    return view! { <span></span> }.into_any();
                }
                view! {
                    <div class="absolute -right-1.5 -top-1.5 flex gap-0.5">
                        <TileButton
                            action=if hidden { "unhide" } else { "hide" }
                            icon=controls.clone()
                            name=if hidden { "eye" } else { "eye-off" }
                            label=if hidden {
                                "desk.desktop.show_workspace"
                            } else {
                                "desk.desktop.hide_workspace"
                            }
                        />
                    </div>
                }
                .into_any()
            }}
        </li>
    }
}

/// One folder: the folder's own icon, opened in a dialog. It is a square like a
/// workspace, so its accent and the count in its caption are what tell the two
/// apart — a folder wears a colour, and says how much is inside.
#[component]
fn FolderTile(
    icon: DeskIcon,
    editing: ReadSignal<bool>,
    over: ReadSignal<Option<Seam>>,
) -> impl IntoView {
    let key = icon
        .icon
        .clone()
        .unwrap_or_else(|| DEFAULT_FOLDER_ICON.to_string());
    let name = icon.id.clone();
    let label = icon.label.clone();
    let accessible = label.clone();
    let count = icon.items.len();
    let color = icon.color.clone().unwrap_or_default();
    // Whether this tile is the one a drag would land on, and a copy of the id for
    // the controls that appear inside the tile while the grid is being arranged.
    let id = name.clone();
    let seam = name.clone();
    let highlighted = Signal::derive(move || over.get().as_ref().is_some_and(|s| s.id == id));
    let side = Signal::derive(move || over.get().and_then(|s| (s.id == seam).then_some(s.after)));
    let actions = name.clone();

    view! {
        <li data-icon=name class="group/tile relative flex w-20 flex-col items-center pb-1">
            <button
                type="button"
                data-name="FolderIcon"
                data-folder=name.clone()
                title=label.clone()
                aria-label=accessible
                draggable=move || editing.get().to_string()
                class=format!("{TILE} {}", folder_classes(&color))
                class:cursor-grab=move || editing.get()
                class:ring-2=highlighted
                class:ring-ring=highlighted
            >
                <DeskGlyph icon=key class="size-9" />
            </button>
            <TileCaption label=label count=count />
            <TileSeam side=side />
            {move || {
                if !editing.get() {
                    return view! { <span></span> }.into_any();
                }
                view! {
                    <div class="absolute -right-1.5 -top-1.5 flex gap-0.5">
                        <TileButton action="edit-folder" icon=actions.clone() name="pencil" label="desk.folder.rename" />
                        <TileButton action="delete-folder" icon=actions.clone() name="trash-2" label="desk.folder.delete_title" />
                    </div>
                }
                .into_any()
            }}
        </li>
    }
}

/// The spoken name of a folder icon swatch.
///
/// The `value` stays the persisted key (`"Folder"`, `"Receipt"`, …) — it is what
/// `set-icon` stores and what the folder reads back — so only the accessible name
/// is translated here. Without this the icon picker announced English words in an
/// otherwise Spanish dialog.
pub(super) fn folder_icon_label(
    i18n: &(impl crate::i18n::Translate + Sync),
    value: &str,
) -> String {
    match value {
        "Folder" => i18n.t("desk.folder.icon.folder"),
        "Boxes" => i18n.t("desk.folder.icon.boxes"),
        "Briefcase" => i18n.t("desk.folder.icon.briefcase"),
        "Building2" => i18n.t("desk.folder.icon.building"),
        "Truck" => i18n.t("desk.folder.icon.truck"),
        "Receipt" => i18n.t("desk.folder.icon.receipt"),
        "Users" => i18n.t("desk.folder.icon.users"),
        "Wrench" => i18n.t("desk.folder.icon.wrench"),
        other => other.to_string(),
    }
}

/// The spoken name of a folder colour swatch; the `value` is the accent key the
/// arrangement stores, not a translated word.
pub(super) fn folder_color_label(
    i18n: &(impl crate::i18n::Translate + Sync),
    value: &str,
) -> String {
    match value {
        "slate" => i18n.t("desk.folder.color.slate"),
        "blue" => i18n.t("desk.folder.color.blue"),
        "emerald" => i18n.t("desk.folder.color.emerald"),
        "amber" => i18n.t("desk.folder.color.amber"),
        "rose" => i18n.t("desk.folder.color.rose"),
        "violet" => i18n.t("desk.folder.color.violet"),
        other => other.to_string(),
    }
}

/// A tile's name: always visible, plain text, in the flow under the icon.
///
/// `min-h-8` reserves two lines even for one-word names, so a long name wrapping
/// to a second line never pushes its row down while a short one does not — and,
/// because the caption is a block in the tile's flex column, the next grid row
/// starts below it instead of over it. `line-clamp-2` keeps an unusually long
/// label to two lines rather than letting it grow the tile without bound.
#[component]
fn TileCaption(label: String, #[prop(optional)] count: Option<usize>) -> impl IntoView {
    let i18n = use_i18n();
    let text = match count {
        Some(0) => i18n.t_with("desk.folder.empty_caption", &[("label", &label)]),
        Some(count) => format!("{label} ({count})"),
        None => label,
    };

    view! {
        <span class="mt-2 line-clamp-2 min-h-8 w-full text-center text-xs leading-4 text-foreground">
            {text}
        </span>
    }
}

/// The bar that says which side of a tile a dropped icon will land on.
///
/// A ring answers "which icon"; this answers "which side of it", and they are
/// two different questions now that a tile is a seam. Without it the two halves
/// of a tile would look identical while landing in different places, which is
/// the same aim-in-the-dark the seam was added to remove.
#[component]
fn TileSeam(side: Signal<Option<bool>>) -> impl IntoView {
    view! {
        {move || match side.get() {
            Some(after) => view! {
                <span
                    aria-hidden="true"
                    // Tall enough for the icon square only: the caption sits
                    // below it, and a bar running through the name would read as
                    // a strike-through.
                    class="pointer-events-none absolute top-2 h-16 w-0.5 rounded-full bg-ring"
                    class:left-1=!after
                    class:right-1=after
                />
            }
            .into_any(),
            None => view! { <span></span> }.into_any(),
        }}
    }
}

/// The small control that appears on a tile while the grid is being arranged.
///
/// `size-8` is the smallest square that is still a comfortable touch target; at
/// `size-6` the control was a 24 px box a finger could miss.
#[component]
fn TileButton(
    action: &'static str,
    icon: String,
    name: &'static str,
    label: &'static str,
) -> impl IntoView {
    let label = use_i18n().t(label);
    view! {
        <button
            type="button"
            data-action=action
            data-icon=icon
            title=label.clone()
            aria-label=label
            class="flex size-8 items-center justify-center rounded-full border bg-background text-muted-foreground shadow-xs transition-colors hover:bg-accent hover:text-foreground focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50 max-md:after:absolute max-md:after:-inset-1 max-md:after:content-['']"
        >
            <Icon name=name class="size-3.5" />
        </button>
    }
}

/// A folder's square: its accent, or the muted default when it wears none.
fn folder_classes(color: &str) -> &'static str {
    FOLDER_COLORS
        .iter()
        .find(|(key, _)| *key == color)
        .map(|(_, classes)| *classes)
        .unwrap_or("ferris-desk-folder--default")
}
